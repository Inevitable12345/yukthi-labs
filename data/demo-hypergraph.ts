/* ============================================================================
   THE STABLE LATTICE, AND THE SAME SYSTEM AFTER RUPTURE
   ----------------------------------------------------------------------------
   Both graphs are `illustrative: true`. They are schematics of two regimes, not
   observations of any particular system.

   The pair is constructed so that the *nodes barely move*. What changes between
   them is topology: routes become conditional, previously independent layers
   couple, two relations break, and policy enters as a node rather than as context.
   That is the argument — a rupture is not a bigger shock, it is a different graph.
   ========================================================================== */

